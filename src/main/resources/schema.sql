create table if not exists track_history(
  id BIGINT generated by default as identity primary key,
  event_fingerprint VARCHAR(64) not null,
    track_id VARCHAR(255) not null,
    timestamp TIMESTAMP(6) with time zone not null ,
    latitude DOUBLE PRECISION not null,
    longitude DOUBLE PRECISION not null,
    altitude DOUBLE PRECISION,
    heading DOUBLE PRECISION,
    identity VARCHAR(255) not null,

    constraint uk_history_fingerprint UNIQUE (event_fingerprint)
);


create table if not exists current_picture(
    track_id VARCHAR(255) primary key,
    timestamp TIMESTAMP(6) with time zone not null ,
    latitude DOUBLE PRECISION not null,
    longitude DOUBLE PRECISION not null,
    altitude DOUBLE PRECISION,
    heading DOUBLE PRECISION,
    identity VARCHAR(255) not null
);

create index if not exists idx_history_track_timestamp
on track_history(track_id, timestamp desc);